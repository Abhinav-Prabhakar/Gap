/**
 * Packaging manifests for a Gap release.
 *
 * The standalone `gap` binary is the distribution unit for Homebrew, Scoop and
 * winget. Given the release version and the `SHA256SUMS` produced by
 * `scripts/build-binaries.sh`, these renderers produce every manifest a tap or
 * store submission needs. They are pure functions so they can be tested and
 * dry-run before anything is published.
 */

export interface ReleaseAsset {
  /** File name exactly as uploaded, e.g. `gap-darwin-arm64.tar.gz`. */
  name: string;
  /** Lowercase or uppercase hex SHA-256. */
  sha256: string;
}

export interface ReleaseManifestOptions {
  version: string;
  /** GitHub repository in `owner/name` form. */
  repository?: string;
  assets: ReleaseAsset[];
  /** ISO date (`YYYY-MM-DD`) recorded by winget. Defaults to today. */
  releaseDate?: string;
}

export interface WingetManifests {
  version: string;
  installer: string;
  locale: string;
}

export interface RenderedManifests {
  homebrew: string;
  scoop: string;
  winget: WingetManifests;
}

const DEFAULT_REPOSITORY = "Abhinav-Prabhakar/Gap";
const PLATFORM_ASSETS = {
  "darwin-arm64": "gap-darwin-arm64.tar.gz",
  "darwin-x64": "gap-darwin-x64.tar.gz",
  "linux-arm64": "gap-linux-arm64.tar.gz",
  "linux-x64": "gap-linux-x64.tar.gz",
  windows: "gap-windows-x64.zip",
} as const;

function normalizeRepository(repository: string): string {
  const trimmed = repository.trim().replace(/^https?:\/\/github\.com\//, "").replace(/\/+$/, "");
  if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(trimmed)) {
    throw new Error(`Expected a GitHub repository like "owner/name", received "${repository}".`);
  }
  return trimmed;
}

function normalizeVersion(version: string): string {
  const trimmed = version.trim().replace(/^v/, "");
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(trimmed)) {
    throw new Error(`Expected a semantic version like "0.1.0", received "${version}".`);
  }
  return trimmed;
}

/** Parse `shasum -a 256` output (`<hash>  <file>`) into release assets. */
export function parseChecksums(text: string): ReleaseAsset[] {
  const assets: ReleaseAsset[] = [];
  for (const line of text.split(/\r?\n/)) {
    const match = line.trim().match(/^([a-fA-F0-9]{64})\s+\*?(.+)$/);
    if (!match) continue;
    assets.push({ sha256: match[1]!.toLowerCase(), name: match[2]!.trim() });
  }
  return assets;
}

function assetMap(assets: readonly ReleaseAsset[]): Map<string, string> {
  const map = new Map<string, string>();
  for (const asset of assets) {
    const name = asset.name.split("/").pop() ?? asset.name;
    if (!/^[a-fA-F0-9]{64}$/.test(asset.sha256)) {
      throw new Error(`Invalid SHA-256 for ${name}: "${asset.sha256}".`);
    }
    map.set(name, asset.sha256.toLowerCase());
  }
  return map;
}

function requireAssets(assets: readonly ReleaseAsset[]): Map<string, string> {
  const map = assetMap(assets);
  const missing = Object.values(PLATFORM_ASSETS).filter((name) => !map.has(name));
  if (missing.length > 0) {
    throw new Error(
      `Missing release assets: ${missing.join(", ")}. Build them with scripts/build-binaries.sh first.`,
    );
  }
  return map;
}

function downloadUrl(repository: string, version: string, asset: string): string {
  return `https://github.com/${repository}/releases/download/v${version}/${asset}`;
}

/** Render `Formula/gap.rb` for a Homebrew tap. */
export function renderHomebrewFormula(options: ReleaseManifestOptions): string {
  const repository = normalizeRepository(options.repository ?? DEFAULT_REPOSITORY);
  const version = normalizeVersion(options.version);
  const assets = requireAssets(options.assets);

  const archBlock = (arch: "arm" | "intel", key: keyof typeof PLATFORM_ASSETS): string => {
    const asset = PLATFORM_ASSETS[key];
    return [
      `    on_${arch} do`,
      `      url "${downloadUrl(repository, version, asset)}"`,
      `      sha256 "${assets.get(asset)}"`,
      `    end`,
    ].join("\n");
  };

  const osBlock = (os: "macos" | "linux", arm: keyof typeof PLATFORM_ASSETS, intel: keyof typeof PLATFORM_ASSETS): string =>
    [`  on_${os} do`, archBlock("arm", arm), archBlock("intel", intel), `  end`].join("\n");

  return `# Generated by \`gap release manifests\`. Do not edit by hand.
class Gap < Formula
  desc "Typed actions for agents: CLI, inspector and MCP tooling"
  homepage "https://github.com/${repository}"
  version "${version}"
  license "MIT"

${osBlock("macos", "darwin-arm64", "darwin-x64")}
${osBlock("linux", "linux-arm64", "linux-x64")}

  def install
    bin.install "gap"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/gap --version")
    assert_match "Gap", shell_output("#{bin}/gap --help")
  end
end
`;
}

/** Render `gap.json` for a Scoop bucket. */
export function renderScoopManifest(options: ReleaseManifestOptions): string {
  const repository = normalizeRepository(options.repository ?? DEFAULT_REPOSITORY);
  const version = normalizeVersion(options.version);
  const assets = requireAssets(options.assets);
  const archive = PLATFORM_ASSETS.windows;

  const manifest = {
    $schema: "https://raw.githubusercontent.com/ScoopInstaller/Scoop/master/schema.json",
    version,
    description: "Typed actions for agents: CLI, inspector and MCP tooling.",
    homepage: `https://github.com/${repository}`,
    license: "MIT",
    architecture: {
      "64bit": {
        url: downloadUrl(repository, version, archive),
        hash: assets.get(archive),
      },
    },
    bin: "gap.exe",
    checkver: { github: `https://github.com/${repository}` },
    autoupdate: {
      architecture: {
        "64bit": {
          url: `https://github.com/${repository}/releases/download/v$version/${archive}`,
          hash: { url: "$url.sha256" },
        },
      },
    },
  };

  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function yamlScalar(value: string): string {
  if (/^[A-Za-z0-9 .,/_()'-]+$/.test(value) && !/^(true|false|null|yes|no|\d+(\.\d+)?)$/i.test(value)) {
    return value;
  }
  return JSON.stringify(value);
}

/** Render the three winget manifests for a portable installer. */
export function renderWingetManifests(options: ReleaseManifestOptions): WingetManifests {
  const repository = normalizeRepository(options.repository ?? DEFAULT_REPOSITORY);
  const version = normalizeVersion(options.version);
  const assets = requireAssets(options.assets);
  const installer = PLATFORM_ASSETS.windows;
  const releaseDate = options.releaseDate ?? new Date().toISOString().slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(releaseDate)) {
    throw new Error(`Expected a release date like 2026-11-22, received "${releaseDate}".`);
  }
  const licenseUrl = `https://github.com/${repository}/blob/main/LICENSE`;

  const versionManifest = `# Generated by \`gap release manifests\`. Do not edit by hand.
PackageIdentifier: AbhinavPrabhakar.Gap
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.10.0
`;

  const installerManifest = `# Generated by \`gap release manifests\`. Do not edit by hand.
PackageIdentifier: AbhinavPrabhakar.Gap
PackageVersion: ${version}
InstallerLocale: en-US
Platform:
  - Windows.Desktop
MinimumOSVersion: 10.0.0.0
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: gap.exe
    PortableCommandAlias: gap
InstallModes:
  - interactive
  - silent
  - silentWithProgress
UpgradeBehavior: install
ReleaseDate: ${releaseDate}
Installers:
  - Architecture: x64
    InstallerUrl: ${downloadUrl(repository, version, installer)}
    InstallerSha256: ${assets.get(installer)!.toUpperCase()}
ManifestType: installer
ManifestVersion: 1.10.0
`;

  const localeManifest = `# Generated by \`gap release manifests\`. Do not edit by hand.
PackageIdentifier: AbhinavPrabhakar.Gap
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Abhinav Prabhakar
PublisherUrl: https://github.com/Abhinav-Prabhakar
PublisherSupportUrl: https://github.com/${repository}/issues
Author: Abhinav Prabhakar
PackageName: Gap
PackageUrl: https://github.com/${repository}
License: MIT
LicenseUrl: ${licenseUrl}
Copyright: Copyright (c) 2026 Abhinav Prabhakar
ShortDescription: ${yamlScalar("Typed actions for agents, with policy, approvals and an MCP server.")}
Description: |
  Gap turns application capabilities into typed, permissioned, auditable actions
  instead of screen automation. One action definition compiles to an MCP tool,
  an OpenAPI operation and a browser DOM binding, with delegated identity,
  argument-bound approvals, policy limits, idempotency, receipts, undo, audit
  and tool-selection evals built in.
Moniker: gap
Tags:
  - mcp
  - agents
  - ai
  - cli
  - model-context-protocol
ReleaseNotesUrl: https://github.com/${repository}/releases/tag/v${version}
Documentations:
  - DocumentLabel: Distribution guide
    DocumentUrl: https://github.com/${repository}/blob/main/docs/distribution.md
ManifestType: defaultLocale
ManifestVersion: 1.10.0
`;

  return { version: versionManifest, installer: installerManifest, locale: localeManifest };
}

/** Render every manifest for a release. */
export function renderManifests(options: ReleaseManifestOptions): RenderedManifests {
  return {
    homebrew: renderHomebrewFormula(options),
    scoop: renderScoopManifest(options),
    winget: renderWingetManifests(options),
  };
}

/** Write manifests into a directory tree mirroring the tap and store repos. */
export function writeManifests(
  options: ReleaseManifestOptions,
  outDir: string,
  writeFile: (file: string, content: string) => void,
  mkdir: (dir: string) => void,
): string[] {
  const rendered = renderManifests(options);
  const version = normalizeVersion(options.version);
  const files: Array<[string, string]> = [
    ["homebrew/Formula/gap.rb", rendered.homebrew],
    ["scoop/bucket/gap.json", rendered.scoop],
    [`winget/manifests/a/AbhinavPrabhakar/Gap/${version}/AbhinavPrabhakar.Gap.yaml`, rendered.winget.version],
    [`winget/manifests/a/AbhinavPrabhakar/Gap/${version}/AbhinavPrabhakar.Gap.installer.yaml`, rendered.winget.installer],
    [`winget/manifests/a/AbhinavPrabhakar/Gap/${version}/AbhinavPrabhakar.Gap.locale.en-US.yaml`, rendered.winget.locale],
  ];
  for (const [relative, content] of files) {
    const file = `${outDir.replace(/\/+$/, "")}/${relative}`;
    const directory = file.slice(0, file.lastIndexOf("/"));
    mkdir(directory);
    writeFile(file, content);
  }
  return files.map(([relative]) => `${outDir.replace(/\/+$/, "")}/${relative}`);
}
